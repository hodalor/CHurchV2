function buildTenantAdminPermissions(enabledNavigation = []) {
  const normalizedKeys = Array.isArray(enabledNavigation)
    ? [...new Set(enabledNavigation.map((item) => String(item || "").trim()).filter(Boolean))]
    : [];

  if (!normalizedKeys.length) {
    return ROLE_PERMISSION_MAP[ROLES.CHURCH_ADMINISTRATOR];
  }

  const parentKeys = [...new Set(normalizedKeys.map((key) => key.split(".")[0]))];
  return [
    ...new Set(
      parentKeys.flatMap((key) => TENANT_NAVIGATION_PERMISSION_MAP[key] || [])
    ),
  ];
}

